`timescale 1ns/1ps

module tb_arbiter;

logic clk;
logic rst;

logic req0;
logic req1;

logic grant0;
logic grant1;


//====================================================
// DUT
//====================================================

arbiter dut (

    .clk(clk),
    .rst(rst),

    .req0(req0),
    .req1(req1),

    .grant0(grant0),
    .grant1(grant1)
);


//====================================================
// ASSERTIONS
//====================================================

arbiter_assertions assertions_inst (

    .clk(clk),
    .rst(rst),

    .req0(req0),
    .req1(req1),

    .grant0(grant0),
    .grant1(grant1)
);


//====================================================
// SCOREBOARD
//====================================================

scoreboard scoreboard_inst (

    .clk(clk),

    .req0(req0),
    .req1(req1),

    .grant0(grant0),
    .grant1(grant1)
);


//====================================================
// COVERAGE
//====================================================

coverage coverage_inst (

    .clk(clk),

    .req0(req0),
    .req1(req1),

    .grant0(grant0),
    .grant1(grant1)
);


//====================================================
// CLOCK
//====================================================

always #5 clk = ~clk;


//====================================================
// TEST FLOW
//====================================================

initial begin

    //------------------------------------------------
    // WAVEFORM DUMP
    //------------------------------------------------

    $dumpfile("arbiter.vcd");

    $dumpvars(0, tb_arbiter);


    //------------------------------------------------
    // INITIAL VALUES
    //------------------------------------------------

    clk  = 0;

    rst  = 1;

    req0 = 0;
    req1 = 0;


    //------------------------------------------------
    // RESET
    //------------------------------------------------

    #20;

    rst = 0;


    //------------------------------------------------
    // TEST 1 : req0 only
    //------------------------------------------------

    req0 = 1;

    #20;

    req0 = 0;

    #20;


    //------------------------------------------------
    // TEST 2 : req1 only
    //------------------------------------------------

    req1 = 1;

    #20;

    req1 = 0;

    #20;


    //------------------------------------------------
    // TEST 3 : simultaneous requests
    //------------------------------------------------

    req0 = 1;
    req1 = 1;

    #100;


    //------------------------------------------------
    // TEST 4 : reset during operation
    //------------------------------------------------

    rst = 1;

    #20;

    rst = 0;

    req0 = 0;
    req1 = 0;

    #20;


    //------------------------------------------------
    // TEST 5 : randomized testing
    //------------------------------------------------

    repeat(50) begin

        req0 = $random;
        req1 = $random;

        #10;

    end


    //------------------------------------------------
    // TEST 6 : rapid toggling
    //------------------------------------------------

    repeat(20) begin

        req0 = ~req0;
        req1 = ~req1;

        #5;

    end


    //------------------------------------------------
    // TEST 7 : long contention
    //------------------------------------------------

    req0 = 1;
    req1 = 1;

    #200;


    //------------------------------------------------
    // FINISH
    //------------------------------------------------

    $display("Simulation Completed Successfully");

    $finish;

end

endmodule